"""Generate complete serialized DTO types from the backend Pydantic contract."""

import argparse
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))


def ts(schema):
    if "$ref" in schema:
        return schema["$ref"].split("/")[-1]
    if "const" in schema:
        return json.dumps(schema["const"], ensure_ascii=False)
    if "enum" in schema:
        return " | ".join(json.dumps(item, ensure_ascii=False) for item in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(ts(part) for part in schema["anyOf"])
    kind = schema.get("type")
    if kind == "array":
        return "Array<" + ts(schema["items"]) + ">"
    if kind == "object":
        return (
            "{\n"
            + "\n".join(
                f"  {name}: {ts(value)};" for name, value in schema.get("properties", {}).items()
            )
            + "\n}"
        )
    return {
        "string": "string",
        "integer": "number",
        "number": "number",
        "boolean": "boolean",
        "null": "null",
    }[kind]


def generated():
    from stay_agent.parallel_search import ParallelSearchRequest, ParallelSearchResponse
    from stay_agent.contracts import (
        QuotesResponse,
        SearchResponse,
        SearchPageRequest,
        TravelPlacesResponse,
        TravelRouteResponse,
        TravelPlaceRequest,
        TravelRouteRequest,
        ConversationState,
        InterpretRequest,
        CancelInterpretRequest,
        RecallInput,
        RecallContinueRequest,
        RecallResponse,
        BranchWalkBatchRequest,
        BranchWalkBatchResponse,
        BranchWalkRouteRequest,
        BranchWalkPair,
        DiscoveryResponse,
        NearbyResolveRequest, NearbyResolveResponse,
        NearbyExploreRequest, NearbyExploreResponse,
        NearbyWalkRequest, NearbyWalkResponse,
        NearbyIdentityStatusRequest, NearbyIdentityConfirmRequest,
        NearbyIdentityRevokeRequest, NearbyIdentityResponse,
        ParallelNearbyExploreRequest, ParallelNearbyExploreResponse,
    )

    schemas = {}
    for model in (
        ParallelSearchRequest,
        ParallelSearchResponse,
        SearchResponse,
        SearchPageRequest,
        QuotesResponse,
        TravelPlacesResponse,
        TravelRouteResponse,
        TravelPlaceRequest,
        TravelRouteRequest,
        ConversationState,
        InterpretRequest,
        CancelInterpretRequest,
        RecallInput,
        RecallContinueRequest,
        RecallResponse,
        BranchWalkBatchRequest,
        BranchWalkBatchResponse,
        BranchWalkRouteRequest,
        BranchWalkPair,
        DiscoveryResponse,
        NearbyResolveRequest, NearbyResolveResponse,
        NearbyExploreRequest, NearbyExploreResponse,
        NearbyWalkRequest, NearbyWalkResponse,
        NearbyIdentityStatusRequest, NearbyIdentityConfirmRequest,
        NearbyIdentityRevokeRequest, NearbyIdentityResponse,
        ParallelNearbyExploreRequest, ParallelNearbyExploreResponse,
    ):
        schema = model.model_json_schema()
        schemas.update(schema.pop("$defs", {}))
        schemas[model.__name__] = schema
    header = "// Generated by scripts/export_web_contract.py. Do not edit.\n"
    result = header + "\n\n".join(
        "export type " + name + " = " + ts(schema) + ";" for name, schema in sorted(schemas.items())
    )
    return (
        result
        + """
export type Hotel = HotelSummary;
export type PlaceType = SearchInput['place_type'];
export type Status = SearchResponse['status'];
export type Health = {
  status:'ok';provider:'rollinggo'|'tuniu';credential_configured:boolean;web_ready:boolean;today_shanghai:string;
  features:{maps:boolean;fare:boolean;llm:boolean;multi_branch_recall:boolean;parallel_search?:boolean};
  data_mode:'offline'|'live';
  dataset:{id:string;label:string;version:string;synthetic:true}|null;
  channels:Record<string,{provider:string;configured:boolean;live_verified:boolean}>;
};
export type CheckpointState = {
  connected:boolean;status:'connected'|'disconnected';disconnected_at:string|null;
  checkpoint_id?:string|null;app_commit?:string|null;saved_at?:string|null;
  search_session_count?:number;conversation_count?:number;resume_available?:boolean;
};
export type CheckpointResume = {
  status:'ready'|'unavailable';checkpoint_id:string|null;saved_at:string|null;
  disconnected_at:string|null;search:SearchResponse|null;conversation:ConversationState|null;
  warnings:string[];error:{code:string;message:string}|null;
};
"""
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    target = ROOT / "frontend/src/types.ts"
    content = generated()
    if args.check:
        matches = target.is_file() and target.read_text(encoding="utf-8") == content
        print("Contract types match" if matches else "Contract types need regeneration")
        return 0 if matches else 1
    target.write_text(content, encoding="utf-8")
    print("Generated frontend/src/types.ts")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
