"""Offline architecture guard for the personal 0.9 modular monolith.

Checks structure and import direction without importing providers, reading .env,
opening runtime SQLite files or performing any HTTP. No file hashes.
"""
from __future__ import annotations

import ast
import json
from pathlib import Path
import subprocess
import tomllib

ROOT = Path(__file__).resolve().parents[1]
BACKEND = ROOT / "backend" / "stay_agent"
FRONTEND = ROOT / "frontend" / "src"
PURE_MODULES = (
    "condition_rules.py",
    "restaurant_roles.py",
    "pricing.py",
    "return_trip.py",
    "travel_rules.py",
    "decision.py",
)
# No domain/pure-rule module may depend on HTTP, persistence, suppliers or the
# application composition root.  New architecture can add explicit exceptions
# only after demonstrating the boundary and tests remain correct.
FORBIDDEN_ROOTS = frozenset({
    "requests", "httpx", "http", "urllib", "socket", "subprocess", "sqlite3",
    "fastapi", "starlette", "uvicorn", "os", "pathlib",
})
FORBIDDEN_RELATIVE = frozenset({
    "providers", "main", "http_boundary", "service", "tuniu_service",
    "storage", "conversation", "conversation_store", "recall", "travel",
    "discovery_service", "offline_app", "checkpoint",
})


def import_violations(source: str) -> list[str]:
    """Find prohibited dependencies in a pure domain module (AST, no imports)."""
    tree = ast.parse(source)
    bad: list[str] = []
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                if alias.name.split(".", 1)[0] in FORBIDDEN_ROOTS:
                    bad.append(alias.name)
                if alias.name.startswith("stay_agent.providers") or alias.name == "stay_agent.main":
                    bad.append(alias.name)
        elif isinstance(node, ast.ImportFrom):
            module = node.module or ""
            if node.level > 0:
                if module and module.split(".", 1)[0] in FORBIDDEN_RELATIVE:
                    bad.append("." * node.level + module)
                if not module:
                    for alias in node.names:
                        if alias.name in FORBIDDEN_RELATIVE:
                            bad.append("." * node.level + alias.name)
            elif (
                module.split(".", 1)[0] in FORBIDDEN_ROOTS
                or module.startswith("stay_agent.providers")
                or module == "stay_agent.main"
            ):
                bad.append(module)
    return sorted(set(bad))


def check(root: Path = ROOT) -> list[str]:
    errors: list[str] = []
    backend = root / "backend/stay_agent"
    frontend = root / "frontend/src"
    expected_files = (
        "backend/stay_agent/main.py",
        "backend/stay_agent/http_boundary.py",
        "backend/stay_agent/contracts.py",
        "backend/stay_agent/providers/data/travel_clients.py",
        "backend/stay_agent/providers/data/rollinggo_client.py",
        "backend/stay_agent/providers/llm/adapters.py",
        "frontend/src/App.tsx",
        "frontend/src/api.ts",
        "frontend/src/types.ts",
        "scripts/dev.py",
        "scripts/tray_server.py",
        "scripts/install_tray_launcher.ps1",
        "launcher/XunqiTray.cs",
        "launcher/StartupWindow.cs",
        "launcher/xunqi.ico",
        "start.cmd",
        "stop.cmd",
        "scripts/export_web_contract.py",
        "scripts/personal_backup.py",
    )
    for name in expected_files:
        if not (root / name).is_file():
            errors.append("Missing required entrypoint: " + name)

    for name in PURE_MODULES:
        path = backend / name
        if not path.is_file():
            errors.append("Missing pure module: " + name)
            continue
        try:
            violations = import_violations(path.read_text(encoding="utf-8"))
        except (SyntaxError, OSError):
            errors.append("Unreadable pure module: " + name)
            continue
        for dependency in violations:
            errors.append(f"Domain boundary violation: {name} -> {dependency}")

    generated = frontend / "types.ts"
    if generated.is_file() and not generated.read_text(encoding="utf-8").startswith(
        "// Generated by scripts/export_web_contract.py. Do not edit."
    ):
        errors.append("Frontend types.ts is not marked as contract-generated")

    try:
        project = tomllib.loads((root / "pyproject.toml").read_text(encoding="utf-8"))
        pkg = json.loads((root / "frontend/package.json").read_text(encoding="utf-8"))
        lock = json.loads((root / "frontend/package-lock.json").read_text(encoding="utf-8"))
        version = project["project"]["version"]
        if any(v != version for v in (
            pkg["version"], lock["version"], lock["packages"][""]["version"],
        )):
            errors.append("Python/frontend/lock versions disagree")
        source = (backend / "main.py").read_text(encoding="utf-8")
        tree = ast.parse(source)
        app_versions = [
            kw.value.value
            for node in ast.walk(tree)
            if isinstance(node, ast.Call)
            and isinstance(node.func, ast.Name) and node.func.id == "FastAPI"
            for kw in node.keywords
            if kw.arg == "version" and isinstance(kw.value, ast.Constant)
        ]
        if app_versions != [version]:
            errors.append("FastAPI version disagrees with project metadata")
    except (OSError, ValueError, KeyError, SyntaxError, TypeError):
        errors.append("Cannot verify local version metadata")

    # Runtime, one-shot probes and sensitive backup ledgers are never committed.
    if root == ROOT:
        try:
            tracked = subprocess.check_output(
                ["git", "-C", str(root), "ls-files", "--", "runtime/"],
                text=True,
                stderr=subprocess.DEVNULL,
            ).strip()
            if tracked:
                errors.append("Runtime files must not be tracked by Git")
        except (OSError, subprocess.CalledProcessError):
            errors.append("Cannot inspect Git runtime tracking")
    return errors


def main() -> int:
    errors = check()
    if errors:
        for error in errors:
            print("ARCHITECTURE_ERROR:", error)
        return 1
    print("ARCHITECTURE_PASS: modular monolith / pure rules / generated types / version / runtime")
    print("Source imports and metadata checked only; no provider or database calls.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
